/* "Build: " is 7 bytes; " passed " is 8, so the placeholders start at 7 and
 * 18 and the text is 29 bytes long. */
#define FIRST_START 7u
#define SECOND_START 18u

static const char initial_text[] =
    "Build: \xEF\xBF\xBC passed \xEF\xBF\xBC pending";

static pt_text_image make_image(uint32_t start, pt_icon_image *image, float width,
                                float height, pt_text_image_align align,
                                const char *alt) {
    pt_text_image result = {0};
    result.start = start;
    result.image = image;
    result.width = width;
    result.height = height;
    result.align = align;
    snprintf(result.alt, sizeof result.alt, "%s", alt);
    return result;
}

int main(void) {
    pt_app *app = pt_app_create("dev.pt.examples.inline_images");
    if (!app) {
        fprintf(stderr, "pt: %s\n", pt_get_last_error());
        return 1;
    }
    pt_app_set_color_scheme(app, pt_color_scheme_dark);
    pt_app_set_accent_color(app, pt_rgb(0x7AA2F7));

    pt_window *window = pt_window_create(app, "Pt Inline Images", 720, 480);
    if (!window) {
        fprintf(stderr, "pt: %s\n", pt_get_last_error());
        pt_app_destroy(app);
        return 1;
    }

    pt_widget *root = pt_window_root(window);
    pt_widget_set_padding(root, 24.0f, 24.0f, 24.0f, 24.0f);
    pt_widget_set_gap(root, 12.0f);

    pt_widget *eyebrow = pt_label_create(root, "INLINE IMAGES  ·  U+FFFC  ·  SIDE TABLE");
    pt_widget_set_font_size(eyebrow, 11.0f);
    pt_widget_set_font_weight(eyebrow, pt_font_weight_semibold);
    pt_widget_set_foreground(eyebrow, pt_rgb(0x7AA2F7));

    pt_widget *intro = pt_label_create(
        root, "The text holds two object replacement characters. One image sits on "
              "the baseline, the other is centred; a third is inserted at the caret.");
    pt_widget_set_font_size(intro, 13.0f);
    pt_widget_set_foreground(intro, pt_rgb(0x9AA7B8));
    pt_widget_set_label_wrap(intro, true);

    pt_widget *area = pt_text_area_create(root, "Build log");
    pt_widget_set_text(area, initial_text);
    pt_widget_set_size(area, 600.0f, 140.0f);

    pt_icon_image *icon = pt_icon_image_load_memory(icon_png, sizeof icon_png);
    if (!icon) {
        fprintf(stderr, "pt: %s\n", pt_get_last_error());
        pt_app_destroy(app);
        return 1;
    }

    /* The third descriptor has a valid image but start 0 is 'B', not a
     * placeholder, so the setter drops it. */
    pt_text_image images[3] = {
        make_image(FIRST_START, icon, 20.0f, 20.0f, pt_text_image_align_baseline,
                   "Passed"),
        make_image(SECOND_START, icon, 24.0f, 24.0f, pt_text_image_align_middle,
                   "Pending"),
        make_image(0u, icon, 16.0f, 16.0f, pt_text_image_align_baseline, "Invalid"),
    };
    if (!pt_widget_set_text_images(area, images, 3)) {
        fprintf(stderr, "inline_images: set_text_images failed\n");
        pt_icon_image_destroy(icon);
        pt_app_destroy(app);
        return 1;
    }

    /* Insert a third placeholder at the end of the text. The widget takes its
     * own reference, so the caller's single handle is dropped once below. */
    size_t length = strlen(pt_widget_get_text(area));
    pt_text_area_set_selection(area, (uint32_t)length, (uint32_t)length);
    pt_text_image inserted =
        make_image(0u, icon, 18.0f, 18.0f, pt_text_image_align_baseline, "Working");
    uint32_t inserted_start = 0;
    bool inserted_ok = pt_text_area_insert_image(area, &inserted, &inserted_start);

    pt_icon_image_destroy(icon);

    /* The widget still owns the images; these getters only borrow the handles. */
    uint32_t count = pt_widget_get_text_image_count(area);
    pt_text_image first = {0};
    pt_text_image second = {0};
    bool first_ok = pt_widget_get_text_image(area, 0, &first);
    bool second_ok = pt_widget_get_text_image(area, 1, &second);

    int failures = 0;
    if (!inserted_ok || inserted_start != 29u) {
        failures++;
    }
    if (count != 3u || !first_ok || !second_ok) {
        failures++;
    }
    if (first.align != pt_text_image_align_baseline ||
        strcmp(first.alt, "Passed") != 0) {
        failures++;
    }
    if (second.align != pt_text_image_align_middle ||
        strcmp(second.alt, "Pending") != 0) {
        failures++;
    }

    pt_widget *status = pt_label_create(root, "");
    pt_widget_set_font_size(status, 12.0f);
    pt_widget_set_foreground(status, pt_rgb(0x9ECE6A));
    pt_widget_set_label_wrap(status, true);
    char summary[512];
    snprintf(summary, sizeof summary,
             "entries=%u  inserted_at=%u  first=%d/%s  second=%d/%s  text_bytes=%zu",
             count, inserted_start, (int)first.align, first.alt, (int)second.align,
             second.alt, strlen(pt_widget_get_text(area)));
    pt_widget_set_text(status, summary);

    pt_widget *footer = pt_label_create(
        root, "The text still contains EF BF BC; the side table is an index over it. "
              "Selection and bidi offsets are unchanged.");
    pt_widget_set_font_size(footer, 12.0f);
    pt_widget_set_foreground(footer, pt_rgb(0x6F7C8F));
    pt_widget_set_label_wrap(footer, true);

    pt_window_show(window);

    const char *headless = getenv("PT_HEADLESS");
    int run_status;
    if (headless && *headless && strcmp(headless, "0") != 0) {
        printf("inline_images: count=%u inserted_start=%u first_align=%d "
               "second_align=%d second_alt=%s text_bytes=%zu\n",
               count, inserted_start, (int)first.align, (int)second.align,
               second.alt, strlen(pt_widget_get_text(area)));
        fflush(stdout);
        run_status = pt_app_run_for(app, 250);
    } else {
        run_status = pt_app_run(app);
    }

    pt_app_destroy(app);
    return failures ? 1 : run_status;
}
