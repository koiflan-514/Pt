/*
 * Pt inline images: two U+FFFC placeholders with different vertical alignment
 * and alt text, then one insertion at the caret.
 * Copyright 2026 The Pt Authors.
 * Licensed under the Apache License, Version 2.0.
 *
 * Contract demonstrated here (include/pt/base.h, include/pt/widget.h):
 *
 *  - U+FFFC (EF BF BC) in the UTF-8 text is the placeholder; the side table
 *    stores one descriptor per placeholder keyed by its byte offset. The text
 *    is the single source of truth, so pt_widget_get_text still returns EF BF BC.
 *  - pt_widget_set_text_images copies the array, drops entries whose start is
 *    not a complete placeholder or whose image is NULL, sorts by start, keeps
 *    the last duplicate and takes its own reference to each image.
 *  - pt_widget_get_text_image copies a descriptor but only lends the image
 *    handle; it stays valid while the side table is alive.
 *  - pt_text_area_insert_image inserts one placeholder at the caret and takes
 *    its own reference, so the caller may destroy its handle afterwards.
 *  - align grows the line metrics: baseline puts the bottom edge on the text
 *    baseline, middle centres the image on it.
 *
 * The 32x32 PNG is embedded so the example needs no asset file.
 */

