typedef struct icon_state {
    pt_app *app;
    pt_window *window;
    pt_widget *tinted;
    pt_widget *lookup;
    pt_widget *status;
    unsigned tint_step;
} icon_state;

static void report(icon_state *state, const char *text) {
    pt_widget_set_text(state->status, text);
}

static void on_tint_cycle(pt_widget *button, void *user_data) {
    (void)button;
    icon_state *state = user_data;
    const pt_color tints[] = {
        0u,
        pt_rgb(0x7AA2F7),
        pt_rgb(0x9ECE6A),
        pt_rgb(0xF7768E),
        pt_rgb(0xE0AF68),
    };
    state->tint_step = (state->tint_step + 1u) % (unsigned)(sizeof(tints) / sizeof(tints[0]));
    pt_color tint = tints[state->tint_step];
    pt_button_set_icon_tint(state->tinted, tint);
    char text[128];
    if (tint == 0u) {
        snprintf(text, sizeof(text), "Tint cleared: the icon shows its own warm colours");
    } else {
        snprintf(text, sizeof(text), "Tint 0x%08X applied to the icon mask", (unsigned)tint);
    }
    report(state, text);
}

static void on_lookup(pt_widget *button, void *user_data) {
    icon_state *state = user_data;
    (void)button;
    pt_icon_image *found = pt_icon_image_from_name("edit-copy", 24);
    if (!found) {
        char text[224];
        snprintf(text, sizeof(text), "hicolor lookup missed (still safe): %s",
                 pt_get_last_error());
        report(state, text);
        return;
    }
    pt_button_set_icon_image(state->lookup, found);
    char text[128];
    snprintf(text, sizeof(text), "Loaded hicolor edit-copy (%dx%d) into the lookup button",
             pt_icon_image_width(found), pt_icon_image_height(found));
    report(state, text);
    pt_icon_image_destroy(found);
}

static void on_quit(pt_widget *button, void *user_data) {
    (void)button;
    pt_app_quit((pt_app *)user_data);
}

int main(void) {
    pt_app *app = pt_app_create("dev.pt.examples.icon_button");
    if (!app) {
        fprintf(stderr, "pt: %s\n", pt_get_last_error());
        return 1;
    }
    pt_app_set_color_scheme(app, pt_color_scheme_dark);
    pt_app_set_accent_color(app, pt_rgb(0x7AA2F7));

    pt_window *window = pt_window_create(app, "Pt Icon Buttons", 680, 520);
    if (!window) {
        fprintf(stderr, "pt: %s\n", pt_get_last_error());
        pt_app_destroy(app);
        return 1;
    }

    icon_state state = {.app = app, .window = window};
    pt_widget *root = pt_window_root(window);
    pt_widget_set_padding(root, 26.0f, 26.0f, 26.0f, 26.0f);
    pt_widget_set_gap(root, 14.0f);

    pt_widget *eyebrow = pt_label_create(root, "ICONS  ·  PNG  ·  TINT");
    pt_widget_set_font_size(eyebrow, 11.0f);
    pt_widget_set_font_weight(eyebrow, pt_font_weight_semibold);
    pt_widget_set_foreground(eyebrow, pt_rgb(0x7AA2F7));

    pt_widget *heading = pt_label_create(root, "Raster icons in button slots");
    pt_widget_set_font_size(heading, 28.0f);
    pt_widget_set_font_weight(heading, pt_font_weight_semibold);

    pt_widget *intro = pt_label_create(
        root, "A 32x32 PNG is decoded from memory and shared by three buttons. The button takes "
              "its own reference; the example drops the loader reference immediately. Tint 0 "
              "keeps the original colours, anything else draws the alpha mask in the theme "
              "colour.");
    pt_widget_set_font_size(intro, 13.0f);
    pt_widget_set_foreground(intro, pt_rgb(0x9AA7B8));
    pt_widget_set_label_wrap(intro, true);

    pt_icon_image *image = pt_icon_image_load_memory(icon_png, sizeof(icon_png));
    if (!image) {
        fprintf(stderr, "pt: %s\n", pt_get_last_error());
        pt_app_destroy(app);
        return 1;
    }

    pt_widget *card = pt_card_create(root);
    pt_widget_set_padding(card, 18.0f, 18.0f, 18.0f, 18.0f);
    pt_widget_set_gap(card, 14.0f);

    pt_widget *icon_only_row = pt_row_create(card);
    pt_widget_set_gap(icon_only_row, 12.0f);
    pt_widget_set_align_self(icon_only_row, pt_align_center);
    pt_widget *icon_only = pt_button_create(icon_only_row, "");
    pt_widget_set_size(icon_only, 52.0f, 46.0f);
    pt_button_set_variant(icon_only, pt_button_secondary);
    pt_button_set_icon_image(icon_only, image);
    pt_widget_set_a11y_name(icon_only, "Icon-only action");
    pt_widget_set_tooltip(icon_only, "Icon-only button: 18 logical px, centred");
    pt_widget *with_text = pt_button_create(icon_only_row, "Icon and label");
    pt_button_set_variant(with_text, pt_button_secondary);
    pt_button_set_icon_image(with_text, image);
    pt_widget_set_tooltip(with_text, "Untinted: the PNG's own warm colours");
    state.tinted = pt_button_create(icon_only_row, "Tinted");
    pt_button_set_variant(state.tinted, pt_button_primary);
    pt_button_set_icon_image(state.tinted, image);
    pt_button_set_icon_tint(state.tinted, pt_rgb(0xF7768E));
    pt_widget_set_tooltip(state.tinted, "Tint replaces RGB but keeps the alpha mask");

    pt_widget *tools = pt_row_create(card);
    pt_widget_set_gap(tools, 10.0f);
    pt_widget *tint_button = pt_button_create(tools, "Cycle tint");
    pt_button_set_variant(tint_button, pt_button_secondary);
    pt_button_set_on_click(tint_button, on_tint_cycle, &state);
    pt_widget *lookup = pt_button_create(tools, "Look up edit-copy");
    pt_button_set_variant(lookup, pt_button_ghost);
    state.lookup = lookup;
    pt_button_set_on_click(lookup, on_lookup, &state);
    pt_widget_set_tooltip(lookup, "Best-effort hicolor lookup; a miss only records an error");

    state.status = pt_label_create(root, "");
    pt_widget_set_font_size(state.status, 12.0f);
    pt_widget_set_foreground(state.status, pt_rgb(0x9ECE6A));
    pt_widget_set_label_wrap(state.status, true);

    /* The window icon is best effort: niri/Sway/Weston and PT_HEADLESS accept
     * it silently, but the getter still reports the retained image. */
    pt_window_set_icon(window, image);
    char summary[192];
    snprintf(summary, sizeof(summary),
             "Loaded %dx%d PNG; button slots hold the image; window icon %s",
             pt_icon_image_width(image), pt_icon_image_height(image),
             pt_window_get_icon(window) ? "retained (best effort)" : "rejected");
    report(&state, summary);
    printf("icon_button: image %dx%d button=%d window=%d\n", pt_icon_image_width(image),
           pt_icon_image_height(image),
           pt_button_get_icon_image(state.tinted) ? 1 : 0,
           pt_window_get_icon(window) ? 1 : 0);
    fflush(stdout);
    pt_icon_image_destroy(image);

    pt_widget *footer = pt_label_create(
        root, "pt_icon_image_destroy() drops a reference; setters hold their own. The last drop "
              "frees decoded pixels and cached rasterisations, so the getters above are borrowed "
              "and valid while the widget or window keeps its reference.");
    pt_widget_set_font_size(footer, 12.0f);
    pt_widget_set_foreground(footer, pt_rgb(0x6F7C8F));
    pt_widget_set_label_wrap(footer, true);

    pt_widget *quit = pt_button_create(root, "Quit");
    pt_button_set_variant(quit, pt_button_ghost);
    pt_button_set_on_click(quit, on_quit, app);
    pt_widget_set_align_self(quit, pt_align_start);

    pt_window_show(window);
    pt_widget_focus(icon_only);

    const char *headless = getenv("PT_HEADLESS");
    int status;
    if (headless && *headless && strcmp(headless, "0") != 0) {
        on_tint_cycle(NULL, &state);
        on_lookup(NULL, &state);
        printf("icon_button: after tint cycle button=%d window=%d\n",
               pt_button_get_icon_image(state.tinted) ? 1 : 0,
               pt_window_get_icon(window) ? 1 : 0);
        fflush(stdout);
        status = pt_app_run_for(app, 250);
    } else {
        status = pt_app_run(app);
    }
    pt_app_destroy(app);
    return status;
}
