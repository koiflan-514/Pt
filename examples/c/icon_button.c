/*
 * Pt PNG icon buttons: a reference-counted raster image in a button slot, an
 * optional theme tint, and a best-effort window icon.
 * Copyright 2026 The Pt Authors.
 * Licensed under the Apache License, Version 2.0.
 *
 * Contract demonstrated here (include/pt/icon.h):
 *
 *  - pt_icon_image is reference counted. A load returns one reference; setters
 *    take their own reference, so the example drops its reference once every
 *    slot has been configured.
 *  - pt_button_set_icon_image lays the image before the text, or centres it for
 *    an icon-only button. NULL clears the slot.
 *  - pt_button_set_icon_tint(button, 0) restores the image's own colours; any
 *    other 0xRRGGBBAA value replaces the RGB with the tint scaled by alpha, so
 *    an alpha-mask glyph follows the theme foreground.
 *  - pt_window_set_icon is best effort. Compositors without
 *    xdg_toplevel_icon_v1 (niri, Sway, Weston) and PT_HEADLESS accept the call
 *    as a silent no-op, but the getter still reports the retained image.
 *
 * The 32x32 PNG below is embedded so the example needs no asset file. It is a
 * warm-coloured ring with a cross bar and a centre dot on a transparent
 * background: untinted buttons show the warm colours, tinted ones show only the
 * glyph mask.
 */

